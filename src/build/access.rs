use std::fs;
use std::path::Path;

use serde::Serialize;

use crate::config::{
    normalize_access_prefix, password_secret_binding, session_secret_binding, SiteConfig,
};
use crate::error::{PageError, Result};

const GENERATED_MARKER: &str = "// Generated by seite password access. Do not edit.";
const GENERATED_ROUTES: &str =
    "{\n  \"version\": 1,\n  \"include\": [\"/*\"],\n  \"exclude\": []\n}\n";

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct AccessRoute {
    pub prefix: String,
    pub group: String,
}

/// Build the ordered route table for this output's config. Subdomain builds
/// already contain one collection rewritten to the root, so the same logic
/// covers paths, whole sites, and whole subdomains.
pub fn access_routes(config: &SiteConfig) -> Vec<AccessRoute> {
    if config.access.is_none() {
        return Vec::new();
    }

    let mut routes = Vec::new();
    for collection in &config.collections {
        let Some(group) = collection.resolved_access_group() else {
            continue;
        };
        let prefix = normalize_access_prefix(&collection.url_prefix);
        routes.push(AccessRoute {
            prefix: prefix.clone(),
            group: group.to_string(),
        });
        if prefix != "/" {
            for lang in config.languages.keys() {
                routes.push(AccessRoute {
                    prefix: format!("/{lang}{prefix}"),
                    group: group.to_string(),
                });
            }
        }
        routes.push(AccessRoute {
            prefix: format!("/private-assets/{group}"),
            group: group.to_string(),
        });
    }

    routes.sort_by(|a, b| {
        b.prefix
            .len()
            .cmp(&a.prefix.len())
            .then_with(|| a.prefix.cmp(&b.prefix))
    });
    routes.dedup();
    routes
}

/// Rust mirror of the generated Worker's route matching, used both to keep the
/// intended boundary explicit and to test the route contract independently.
pub fn matching_group<'a>(routes: &'a [AccessRoute], path: &str) -> Option<&'a str> {
    let decoded_path = urlencoding::decode(path).ok()?;
    if decoded_path.contains('\\')
        || decoded_path
            .split('/')
            .any(|segment| segment == "." || segment == "..")
    {
        return None;
    }
    routes
        .iter()
        .find(|route| {
            route.prefix == "/"
                || decoded_path == route.prefix
                || decoded_path.starts_with(&format!("{}/", route.prefix))
                || decoded_path == format!("{}.md", route.prefix)
                || decoded_path == format!("{}.html", route.prefix)
        })
        .map(|route| route.group.as_str())
}

/// Write the generated Cloudflare Pages advanced-mode Worker. Returns true
/// when access is active for this output.
pub fn write_worker(config: &SiteConfig, output: &Path) -> Result<bool> {
    let routes = access_routes(config);
    if config.access.is_none() {
        return Ok(false);
    }
    validate_routes(&routes)?;

    validate_generated_file_conflicts(output)?;

    let worker_path = output.join("_worker.js");
    let routes_path = output.join("_routes.json");
    let session_hours = config.access.as_ref().map_or(168, |a| a.session_hours);
    fs::write(worker_path, generate_worker(&routes, session_hours))?;
    fs::write(routes_path, GENERATED_ROUTES)?;
    Ok(true)
}

pub(crate) fn validate_generated_file_conflicts(directory: &Path) -> Result<()> {
    let worker_path = directory.join("_worker.js");
    if worker_path.exists() {
        let existing = fs::read_to_string(&worker_path)?;
        if !existing.starts_with(GENERATED_MARKER) {
            return Err(PageError::Build(
                "password access cannot generate _worker.js because public/_worker.js already exists"
                    .into(),
            ));
        }
    }

    let routes_path = directory.join("_routes.json");
    if routes_path.exists() {
        let existing = fs::read_to_string(&routes_path)?;
        if existing != GENERATED_ROUTES {
            return Err(PageError::Build(
                "password access cannot generate _routes.json because public/_routes.json already exists and could bypass authentication"
                    .into(),
            ));
        }
    }
    Ok(())
}

fn validate_routes(routes: &[AccessRoute]) -> Result<()> {
    let mut groups_by_prefix = std::collections::BTreeMap::new();
    for route in routes {
        if let Some(existing_group) = groups_by_prefix.insert(&route.prefix, &route.group) {
            if existing_group != &route.group {
                return Err(PageError::Build(format!(
                    "password access route '{}' belongs to both '{}' and '{}'; change the language code, url_prefix, or access_group so every protected path has one password group",
                    route.prefix, existing_group, route.group
                )));
            }
        }
    }
    Ok(())
}

pub fn generate_worker(routes: &[AccessRoute], session_hours: u32) -> String {
    let route_json = serde_json::to_string(routes).unwrap_or_else(|_| "[]".into());
    let mut password_bindings = serde_json::Map::new();
    let mut session_bindings = serde_json::Map::new();
    for route in routes {
        password_bindings.insert(
            route.group.clone(),
            serde_json::Value::String(password_secret_binding(&route.group)),
        );
        session_bindings.insert(
            route.group.clone(),
            serde_json::Value::String(session_secret_binding(&route.group)),
        );
    }
    let password_binding_json =
        serde_json::to_string(&password_bindings).unwrap_or_else(|_| "{}".into());
    let session_binding_json =
        serde_json::to_string(&session_bindings).unwrap_or_else(|_| "{}".into());

    WORKER_TEMPLATE
        .replace("__ROUTES__", &route_json)
        .replace("__PASSWORD_BINDINGS__", &password_binding_json)
        .replace("__SESSION_BINDINGS__", &session_binding_json)
        .replace(
            "__SESSION_SECONDS__",
            &(u64::from(session_hours) * 3600).to_string(),
        )
}

const WORKER_TEMPLATE: &str = r#"// Generated by seite password access. Do not edit.
const ROUTES = __ROUTES__;
const PASSWORD_BINDINGS = __PASSWORD_BINDINGS__;
const SESSION_BINDINGS = __SESSION_BINDINGS__;
const SESSION_SECONDS = __SESSION_SECONDS__;
const LOGIN_PATH = "/_seite/access/login";
const LOGOUT_PATH = "/_seite/access/logout";
const LEGACY_PRIVATE_PREFIX = "/static/private";
const encoder = new TextEncoder();

function pathMatches(prefix, path) {
  return prefix === "/" || path === prefix || path.startsWith(prefix + "/") || path === prefix + ".md" || path === prefix + ".html";
}

function routeFor(path) {
  return ROUTES.find((route) => pathMatches(route.prefix, path));
}

function decodePath(path) {
  try {
    const decoded = decodeURIComponent(path);
    if (decoded.includes("\\") || decoded.split("/").some((segment) => segment === "." || segment === "..")) return null;
    return decoded;
  } catch {
    return null;
  }
}

function cookieName(group) {
  return "__Host-seite_" + group;
}

function readCookie(request, name) {
  const header = request.headers.get("Cookie") || "";
  for (const part of header.split(";")) {
    const index = part.indexOf("=");
    if (index !== -1 && part.slice(0, index).trim() === name) return part.slice(index + 1).trim();
  }
  return null;
}

function base64url(bytes) {
  let binary = "";
  for (const byte of new Uint8Array(bytes)) binary += String.fromCharCode(byte);
  return btoa(binary).replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/, "");
}

async function hmac(secret, value) {
  const key = await crypto.subtle.importKey("raw", encoder.encode(secret), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  return crypto.subtle.sign("HMAC", key, encoder.encode(value));
}

async function issueSession(group, secret) {
  const expires = Math.floor(Date.now() / 1000) + SESSION_SECONDS;
  const payload = group + "." + expires;
  const signature = base64url(await hmac(secret, payload));
  return payload + "." + signature;
}

async function validSession(token, group, secret) {
  if (!token) return false;
  const parts = token.split(".");
  if (parts.length !== 3 || parts[0] !== group) return false;
  const expires = Number(parts[1]);
  if (!Number.isSafeInteger(expires) || expires <= Math.floor(Date.now() / 1000)) return false;
  const expected = base64url(await hmac(secret, parts[0] + "." + parts[1]));
  const actualBytes = encoder.encode(parts[2]);
  const expectedBytes = encoder.encode(expected);
  return actualBytes.byteLength === expectedBytes.byteLength && crypto.subtle.timingSafeEqual(actualBytes, expectedBytes);
}

async function passwordMatches(candidate, expected) {
  const candidateHash = await crypto.subtle.digest("SHA-256", encoder.encode(candidate));
  const expectedHash = await crypto.subtle.digest("SHA-256", encoder.encode(expected));
  return crypto.subtle.timingSafeEqual(candidateHash, expectedHash);
}

function safeNext(value) {
  return typeof value === "string" && value.startsWith("/") && !value.startsWith("//") ? value : "/";
}

function escapeHtml(value) {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
}

function htmlResponse(body, status = 200, headers = {}) {
  return new Response(body, {
    status,
    headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store", "X-Robots-Tag": "noindex, nofollow", ...headers },
  });
}

function loginPage(group, next, failed = false) {
  const error = failed ? '<p role="alert">Incorrect password.</p>' : "";
  return `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>Private page</title><style>body{font:16px system-ui;max-width:28rem;margin:15vh auto;padding:1.5rem}form{display:grid;gap:1rem}input,button{font:inherit;padding:.75rem}button{cursor:pointer}</style><main><h1>Private page</h1>${error}<form method="post" action="${LOGIN_PATH}"><input type="hidden" name="group" value="${escapeHtml(group)}"><input type="hidden" name="next" value="${escapeHtml(safeNext(next))}"><label>Password <input name="password" type="password" required autofocus autocomplete="current-password"></label><button type="submit">Continue</button></form></main></html>`;
}

function unavailable() {
  return new Response("<!doctype html><title>Access unavailable</title><h1>Access unavailable</h1>", {
    status: 503,
    headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store", "X-Robots-Tag": "noindex, nofollow" },
  });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const requestPath = decodePath(url.pathname);
    if (requestPath === null) return new Response("Bad Request", { status: 400, headers: { "Cache-Control": "no-store" } });
    if (pathMatches(LEGACY_PRIVATE_PREFIX, requestPath)) return new Response("Not Found", { status: 404, headers: { "Cache-Control": "no-store", "X-Robots-Tag": "noindex, nofollow" } });

    if (requestPath === LOGIN_PATH && request.method === "POST") {
      const form = await request.formData();
      const group = String(form.get("group") || "");
      const next = safeNext(String(form.get("next") || "/"));
      const passwordBinding = PASSWORD_BINDINGS[group];
      const sessionBinding = SESSION_BINDINGS[group];
      const password = passwordBinding ? env[passwordBinding] : null;
      const sessionSecret = sessionBinding ? env[sessionBinding] : null;
      if (!passwordBinding || !sessionBinding || typeof password !== "string" || typeof sessionSecret !== "string") return unavailable();
      if (!(await passwordMatches(String(form.get("password") || ""), password))) return htmlResponse(loginPage(group, next, true), 401);
      const token = await issueSession(group, sessionSecret);
      const cookie = `${cookieName(group)}=${token}; Max-Age=${SESSION_SECONDS}; Path=/; Secure; HttpOnly; SameSite=Lax`;
      return new Response(null, { status: 303, headers: { Location: next, "Set-Cookie": cookie, "Cache-Control": "no-store" } });
    }

    if (requestPath === LOGOUT_PATH && request.method === "POST") {
      if (request.headers.get("Origin") !== url.origin) return new Response("Forbidden", { status: 403, headers: { "Cache-Control": "no-store" } });
      const form = await request.formData();
      const group = String(form.get("group") || "");
      const next = safeNext(String(form.get("next") || "/"));
      const cookie = `${cookieName(group)}=; Max-Age=0; Path=/; Secure; HttpOnly; SameSite=Lax`;
      return new Response(null, { status: 303, headers: { Location: next, "Set-Cookie": cookie, "Cache-Control": "no-store" } });
    }

    const route = routeFor(requestPath);
    if (!route) return env.ASSETS.fetch(request);

    const passwordBinding = PASSWORD_BINDINGS[route.group];
    const sessionBinding = SESSION_BINDINGS[route.group];
    const sessionSecret = sessionBinding ? env[sessionBinding] : null;
    if (!passwordBinding || !sessionBinding || typeof env[passwordBinding] !== "string" || typeof sessionSecret !== "string") return unavailable();
    const token = readCookie(request, cookieName(route.group));
    if (await validSession(token, route.group, sessionSecret)) return env.ASSETS.fetch(request);
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("Unauthorized", { status: 401, headers: { "Cache-Control": "no-store" } });
    return htmlResponse(loginPage(route.group, url.pathname + url.search));
  },
};
"#;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{AccessSection, CollectionConfig, SiteConfig};

    fn config_with(collections: Vec<CollectionConfig>) -> SiteConfig {
        let source = r#"
collections = []

[site]
title = "Test"
base_url = "https://example.com"

[access]
mode = "password"
session_hours = 24
"#;
        let mut config: SiteConfig = toml::from_str(source).unwrap();
        config.collections = collections;
        config.access = Some(AccessSection::default());
        config.access.as_mut().unwrap().session_hours = 24;
        config
    }

    #[test]
    fn access_routes_use_most_specific_prefix_first() {
        let mut root = CollectionConfig::preset_pages();
        root.private = true;
        root.access_group = Some("site".into());
        let mut admin = CollectionConfig::preset_docs();
        admin.private = true;
        admin.url_prefix = "/admin".into();
        admin.access_group = Some("admin".into());

        let routes = access_routes(&config_with(vec![root, admin]));

        assert_eq!(routes[0].prefix, "/private-assets/admin");
        assert_eq!(routes[0].group, "admin");
        assert_eq!(routes[1].prefix, "/private-assets/site");
        assert_eq!(routes[2].prefix, "/admin");
        assert_eq!(routes[3].prefix, "/");
    }

    #[test]
    fn access_route_matching_respects_path_boundaries() {
        let routes = vec![AccessRoute {
            prefix: "/members".into(),
            group: "members".into(),
        }];

        assert_eq!(matching_group(&routes, "/members"), Some("members"));
        assert_eq!(matching_group(&routes, "/members/profile"), Some("members"));
        assert_eq!(matching_group(&routes, "/members.md"), Some("members"));
        assert_eq!(matching_group(&routes, "/membership"), None);
    }

    #[test]
    fn access_route_matching_decodes_asset_paths_before_authorizing() {
        let routes = vec![
            AccessRoute {
                prefix: "/private-assets/staff".into(),
                group: "staff".into(),
            },
            AccessRoute {
                prefix: "/docs".into(),
                group: "docs".into(),
            },
        ];

        assert_eq!(
            matching_group(&routes, "/private-assets%2Fstaff/secret.pdf"),
            Some("staff")
        );
        assert_eq!(matching_group(&routes, "/docs%2Fsecret.md"), Some("docs"));
        assert_eq!(matching_group(&routes, "/docs%ZZsecret.md"), None);
        assert_eq!(matching_group(&routes, "/public/..%2Fdocs/secret.md"), None);
        assert_eq!(matching_group(&routes, "/public%5Cdocs/secret.md"), None);
    }

    #[test]
    fn access_routes_include_translated_collection_paths() {
        let mut docs = CollectionConfig::preset_docs();
        docs.private = true;
        docs.url_prefix = "/docs".into();
        docs.access_group = Some("staff".into());
        let mut config = config_with(vec![docs]);
        config.languages.insert("de".into(), Default::default());

        let routes = access_routes(&config);

        assert!(routes
            .iter()
            .any(|route| { route.prefix == "/de/docs" && route.group == "staff" }));
    }

    #[test]
    fn root_access_does_not_shadow_explicit_language_prefixed_groups() {
        let mut root = CollectionConfig::preset_pages();
        root.private = true;
        root.access_group = Some("site".into());
        let mut explicit_de = CollectionConfig::preset_docs();
        explicit_de.private = true;
        explicit_de.url_prefix = "/de".into();
        explicit_de.access_group = Some("admin".into());
        let mut config = config_with(vec![root, explicit_de]);
        config.languages.insert("de".into(), Default::default());

        let routes = access_routes(&config);

        assert_eq!(matching_group(&routes, "/de/secret"), Some("admin"));
        assert_eq!(
            routes.iter().filter(|route| route.prefix == "/de").count(),
            1
        );
    }

    #[test]
    fn write_worker_rejects_translated_route_group_collisions() {
        let mut docs = CollectionConfig::preset_docs();
        docs.private = true;
        docs.url_prefix = "/docs".into();
        docs.access_group = Some("staff".into());
        let mut explicit_de = CollectionConfig::preset_pages();
        explicit_de.private = true;
        explicit_de.url_prefix = "/de/docs".into();
        explicit_de.access_group = Some("admin".into());
        let mut config = config_with(vec![docs, explicit_de]);
        config.languages.insert("de".into(), Default::default());
        let tmp = tempfile::tempdir().unwrap();

        let error = write_worker(&config, tmp.path()).unwrap_err().to_string();

        assert!(error.contains("route '/de/docs'"));
        assert!(error.contains("'staff'"));
        assert!(error.contains("'admin'"));
    }

    #[test]
    fn write_worker_rejects_routes_that_can_bypass_authentication() {
        let mut docs = CollectionConfig::preset_docs();
        docs.private = true;
        docs.access_group = Some("staff".into());
        let config = config_with(vec![docs]);
        let tmp = tempfile::tempdir().unwrap();
        fs::write(
            tmp.path().join("_routes.json"),
            r#"{"version":1,"include":["/api/*"],"exclude":[]}"#,
        )
        .unwrap();

        let error = write_worker(&config, tmp.path()).unwrap_err().to_string();

        assert!(error.contains("public/_routes.json"));
    }

    #[test]
    fn write_worker_generates_fail_closed_pages_routes() {
        let mut docs = CollectionConfig::preset_docs();
        docs.private = true;
        docs.access_group = Some("staff".into());
        let config = config_with(vec![docs]);
        let tmp = tempfile::tempdir().unwrap();

        write_worker(&config, tmp.path()).unwrap();

        let routes = fs::read_to_string(tmp.path().join("_routes.json")).unwrap();
        assert_eq!(
            serde_json::from_str::<serde_json::Value>(&routes).unwrap(),
            serde_json::json!({"version": 1, "include": ["/*"], "exclude": []})
        );
    }

    #[test]
    fn write_worker_denies_legacy_private_assets_without_active_routes() {
        let config = config_with(Vec::new());
        let tmp = tempfile::tempdir().unwrap();

        assert!(write_worker(&config, tmp.path()).unwrap());

        let worker = fs::read_to_string(tmp.path().join("_worker.js")).unwrap();
        assert!(worker.contains(r#"LEGACY_PRIVATE_PREFIX = "/static/private""#));
        assert!(worker.contains("status: 404"));
    }

    #[test]
    fn generated_worker_uses_group_bindings_and_fail_closed_auth() {
        let routes = vec![AccessRoute {
            prefix: "/members".into(),
            group: "team-alpha".into(),
        }];

        let worker = generate_worker(&routes, 24);

        assert!(worker.contains("SEITE_PASSWORD_TEAM_ALPHA"));
        assert!(worker.contains("SEITE_SESSION_SECRET_TEAM_ALPHA"));
        assert!(worker.contains("request.headers.get(\"Origin\") !== url.origin"));
        assert!(worker.contains("status: 403"));
        assert!(worker.contains("timingSafeEqual"));
        assert!(worker.contains(r#"segment === "." || segment === "..""#));
        assert!(worker.contains(r#"decoded.includes("\\")"#));
        assert!(worker.contains("HMAC"));
        assert!(worker.contains("HttpOnly"));
        assert!(worker.contains("SameSite=Lax"));
        assert!(worker.contains("env.ASSETS.fetch(request)"));
        assert!(worker.contains("status: 503"));
        assert!(!worker.contains("team alpha password"));
    }

    #[test]
    fn binding_name_normalizes_group_identifier() {
        assert_eq!(
            password_secret_binding("team-alpha"),
            "SEITE_PASSWORD_TEAM_ALPHA"
        );
        assert_eq!(password_secret_binding("staff_2"), "SEITE_PASSWORD_STAFF_2");
        assert_eq!(
            crate::config::session_secret_binding("team-alpha"),
            "SEITE_SESSION_SECRET_TEAM_ALPHA"
        );
    }
}
