    #[test]
    fn markdown_worker_only_on_cloudflare_opt_in() {
        let mut config = config_with(Vec::new());
        config.access = None;
        assert!(!worker_enabled(&config));
        config.deploy.markdown_negotiation = true;
        assert!(!worker_enabled(&config), "github-pages: no Worker");
        config.deploy.target = DeployTarget::Netlify;
        assert!(!worker_enabled(&config), "netlify: no Worker");
        config.deploy.target = DeployTarget::Cloudflare;
        assert!(worker_enabled(&config));

        let tmp = tempfile::tempdir().unwrap();
        assert!(write_worker(&config, tmp.path()).unwrap());
        let worker = fs::read_to_string(tmp.path().join("_worker.js")).unwrap();
        assert!(worker.starts_with(MARKDOWN_MARKER));
        assert!(worker.contains("serveAsset(request, env, requestPath, () => true)"));
        assert!(!worker.contains("LOGIN_PATH"));
        let routes = fs::read_to_string(tmp.path().join("_routes.json")).unwrap();
        assert_eq!(routes, MARKDOWN_ROUTES);
        assert!(serde_json::from_str::<serde_json::Value>(&routes).is_ok());

        // Regenerating over its own output (incremental builds) is allowed,
        // and so is switching to password access.
        assert!(write_worker(&config, tmp.path()).unwrap());
        let mut with_access = config_with(Vec::new());
        with_access.deploy.target = DeployTarget::Cloudflare;
        assert!(write_worker(&with_access, tmp.path()).unwrap());
    }

